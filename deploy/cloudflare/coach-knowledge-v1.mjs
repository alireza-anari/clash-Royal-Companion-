    const entities=new Set(coachKnowledgeExpand(coachKnowledgeTokens(doc.entities.join(' '))));
    const body=new Set(coachKnowledgeExpand(coachKnowledgeTokens(doc.content)));
    let score=0;
    for(const token of tokens){
      if(title.has(token))score+=5;
      if(entities.has(token))score+=4;
      if(tags.has(token))score+=3;
      if(body.has(token))score+=1;
    }
    if(action&&doc.actions.includes(action))score+=2;
    for(const entity of doc.entities)if(entity.length>3&&query.includes(coachKnowledgeNormalize(entity)))score+=5;

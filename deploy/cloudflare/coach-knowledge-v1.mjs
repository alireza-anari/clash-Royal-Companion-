function coachKnowledgeNormalize(value){
  return String(value||'').toLowerCase().normalize('NFKC').replace(/ي/g,'ی').replace(/ك/g,'ک').replace(/[\u200c\u200f\u202a-\u202e]/g,' ').replace(/[’']/g,' ').replace(/[^a-z0-9\u0600-\u06ff]+/g,' ').trim();
}
function coachKnowledgeTokens(value){
  const stop=new Set(['the','and','for','with','from','what','when','where','how','does','can','you','your','are','is','a','an','to','of','in','on','my','me','please','من','از','به','برای','که','و','را','در','این','آن','اون','چی','چیه','چطور','چه','می','میشه','میخواهم','میخوام','درباره','آیا']);
  return [...new Set(coachKnowledgeNormalize(value).split(/\s+/).filter(t=>t.length>1&&!stop.has(t)))];
}
